-- Families read their own orders and nothing else. Every WRITE is service-role or admin --
-- matching bookings_no_direct_parent_insert, so a parent cannot invent a paid order.
drop policy if exists "Parents can view own merch orders" on public.merch_orders;
create policy "Parents can view own merch orders"
  on public.merch_orders for select to authenticated
  using (auth.uid() = parent_id or public.has_role(auth.uid(), 'admin'));

drop policy if exists "Admins manage merch orders" on public.merch_orders;
create policy "Admins manage merch orders"
  on public.merch_orders for all to authenticated
  using (public.has_role(auth.uid(), 'admin'))
  with check (public.has_role(auth.uid(), 'admin'));

drop policy if exists "Parents can view own merch order items" on public.merch_order_items;
create policy "Parents can view own merch order items"
  on public.merch_order_items for select to authenticated
  using (
    public.has_role(auth.uid(), 'admin')
    or exists (
      select 1 from public.merch_orders o
      where o.id = merch_order_items.order_id and o.parent_id = auth.uid()
    )
  );

drop policy if exists "Admins manage merch order items" on public.merch_order_items;
create policy "Admins manage merch order items"
  on public.merch_order_items for all to authenticated
  using (public.has_role(auth.uid(), 'admin'))
  with check (public.has_role(auth.uid(), 'admin'));

drop policy if exists "Parents can view own merch personalisation" on public.merch_order_item_personalisations;
create policy "Parents can view own merch personalisation"
  on public.merch_order_item_personalisations for select to authenticated
  using (
    public.has_role(auth.uid(), 'admin')
    or exists (
      select 1
      from public.merch_order_items i
      join public.merch_orders o on o.id = i.order_id
      where i.id = merch_order_item_personalisations.order_item_id and o.parent_id = auth.uid()
    )
  );

drop policy if exists "Admins manage merch personalisation" on public.merch_order_item_personalisations;
create policy "Admins manage merch personalisation"
  on public.merch_order_item_personalisations for all to authenticated
  using (public.has_role(auth.uid(), 'admin'))
  with check (public.has_role(auth.uid(), 'admin'));

-- Print runs are Amie's business only. Staff get no policy on any of these tables at all --
-- coaches see exactly what the collection RPCs return and nothing more.
drop policy if exists "Admins manage merch print runs" on public.merch_print_runs;
create policy "Admins manage merch print runs"
  on public.merch_print_runs for all to authenticated
  using (public.has_role(auth.uid(), 'admin'))
  with check (public.has_role(auth.uid(), 'admin'));

